"""파일명 및 텍스트 정규화 유틸리티 모듈.

이 모듈은 AutoStudy_UI 프로젝트의 전체 파이프라인 중 **Utils(유틸리티) 계층**에 속합니다.
이기종 운영체제(macOS와 Windows/Linux) 간의 파일명 및 텍스트 인코딩 불일치를 해결하고
양끝 공백 정리를 수행하는 순수 유틸리티 함수들을 제공합니다.

macOS는 NFD(자소 분리) 방식을 주로 사용하는 반면, Windows 및 Linux는 NFC(자소 결합) 방식을 사용하므로,
동일해 보이는 파일명이라도 바이트 레벨에서 다르게 인식될 수 있습니다. 이 모듈은 이러한 불일치로 인한
파일 경로 에러, 검색 누락 등을 방지하기 위해 텍스트 표준화를 담당합니다.
"""

import unicodedata

def normalize_text(text: str) -> str:
    """문자열의 양끝 공백을 제거하고 유니코드 NFC(자소 결합) 형태로 정규화합니다.

    이 함수는 주로 이기종 운영체제 간의 텍스트 처리 방식 불일치를 해결하기 위해 필수적으로 요구됩니다.
    예를 들어, macOS는 파일 이름이나 한글 텍스트를 저장할 때 NFD(Normalization Form Canonical 
    Decomposition, 자소 분리) 방식을 사용하여 '한'을 'ㅎ', 'ㅏ', 'ㄴ'으로 분리해 저장하는 반면, 
    Windows 및 Linux 기반의 대부분의 웹/DB 환경에서는 NFC(Normalization Form Canonical Composition, 
    자소 결합) 방식을 표준으로 사용합니다. 
    이러한 인코딩 방식의 차이로 인해 시각적으로는 동일한 문자열이라도 시스템 내부의 바이트 레벨에서는 
    다르게 인식되며, 이는 문자열 검색 실패, 데이터베이스의 유니크 제약 조건 위반, 데이터 중복 적재, 
    잘못된 파일 경로 참조 등 치명적인 버그를 유발할 수 있습니다. 
    따라서 이 로직은 특정 도메인에 국한되지 않고 시스템의 최전방에서 모든 텍스트 데이터를 안전하게 
    표준화(NFC)하여 시스템 전반의 무결성과 데이터 호환성을 유지하는 매우 중요한 역할을 합니다.

    Args:
        text (str): 유니코드 정규화 및 양끝 공백 제거 처리를 수행할 대상 원본 문자열 데이터입니다.
            문자열 타입이 들어오는 것을 기대하지만, 내부적으로 `str()` 캐스팅을 통해 처리하므로
            다른 타입이 들어와도 에러를 방지합니다.

    Returns:
        str: 문자열 양쪽의 공백(Whitespace)이 모두 제거되고, NFC 기반으로 완전히 자소가 결합된 정규화 문자열입니다.
            입력된 `text`가 `None`이거나 빈 문자열(Falsy 한 값)일 경우, 안전하게 `""`(빈 문자열)을 반환합니다.
    """
    if not text:
        return ""
    return unicodedata.normalize('NFC', str(text).strip())